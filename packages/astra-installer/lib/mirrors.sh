# Package source and mirror handling.
#
# The installer can use the pinned Arch Linux Archive snapshot (default,
# reproducible) or a regional set of HTTPS mirrors.  The chosen source is used
# both for pacstrap and for the installed system's /etc/pacman.d/mirrorlist.

# Read and validate the date pinned into the live image.
read_snapshot() {
	local snap
	[[ -r ${SNAPSHOT_FILE} ]] || die "missing snapshot file: ${SNAPSHOT_FILE}"
	snap="$(tr -d '[:space:]' <"${SNAPSHOT_FILE}")"
	[[ ${snap} =~ ^[0-9]{4}/[0-9]{2}/[0-9]{2}$ ]] ||
		die "invalid snapshot date in the live image: ${snap}"
	printf '%s' "${snap}"
}

# Print base mirror URLs (without /$repo/os/$arch) for a region.
mirror_base_urls() {
	local region=${1:-Worldwide}
	case "${region}" in
	Europe)
		cat <<'EOF'
https://archlinux.mirror.liteserver.nl
https://mirrors.xtom.de/archlinux
https://geo.mirror.pkgbuild.com
EOF
		;;
	"North America")
		cat <<'EOF'
https://mirrors.ocf.berkeley.edu/archlinux
https://mirror.csclub.uwaterloo.ca/archlinux
https://mirrors.kernel.org/archlinux
EOF
		;;
	Asia)
		cat <<'EOF'
https://mirrors.tuna.tsinghua.edu.cn/archlinux
https://geo.mirror.pkgbuild.com
https://mirrors.kernel.org/archlinux
EOF
		;;
	Australia)
		cat <<'EOF'
https://mirror.aarnet.edu.au/pub/archlinux
https://geo.mirror.pkgbuild.com
EOF
		;;
	"South America")
		cat <<'EOF'
https://mirror.ufscar.br/archlinux
https://geo.mirror.pkgbuild.com
EOF
		;;
	Africa)
		# There is no reliable country-specific pkgbuild.com host.  Use the
		# global CDN plus two long-lived mirrors rather than a broken hostname.
		cat <<'EOF'
https://geo.mirror.pkgbuild.com
https://mirror.rackspace.com/archlinux
https://mirrors.kernel.org/archlinux
EOF
		;;
	*)
		cat <<'EOF'
https://geo.mirror.pkgbuild.com
https://mirrors.kernel.org/archlinux
https://mirror.rackspace.com/archlinux
EOF
		;;
	esac
}

# Emit [core]/[extra]/[multilib] sections for a pacman.conf.  $repo and $arch
# are expanded by pacman itself.
pacman_repo_sections() {
	local repo base snap
	if [[ ${STATE[mirror_source]} == "ala" ]]; then
		snap="$(read_snapshot)"
		for repo in core extra multilib; do
			printf '\n[%s]\n' "${repo}"
			printf 'Server = https://archive.archlinux.org/repos/%s/$repo/os/$arch\n' "${snap}"
		done
	else
		for repo in core extra multilib; do
			printf '\n[%s]\n' "${repo}"
			while IFS= read -r base; do
				[[ -n ${base} ]] || continue
				printf 'Server = %s/$repo/os/$arch\n' "${base}"
			done < <(mirror_base_urls "${STATE[mirror_region]}")
		done
	fi
}

write_install_pacman_conf() {
	local target=${1:-${PACMAN_CONF}}
	mkdir -p "$(dirname -- "${target}")" || die "cannot create $(dirname -- "${target}")"
	{
		cat <<'EOF'
[options]
Architecture = x86_64
HoldPkg = pacman glibc
ParallelDownloads = 3
SigLevel = Required DatabaseOptional
LocalFileSigLevel = Optional
Color
CheckSpace
ILoveCandy
EOF
		pacman_repo_sections
		if [[ -r ${ASTRA_REPO_DIR}/x86_64/astra-local.db ]]; then
			cat <<EOF

[astra-local]
SigLevel = Optional TrustAll
Server = file://${ASTRA_REPO_DIR}/\$arch
EOF
		fi
	} >"${target}" || die "cannot write ${target}"
	log "wrote install pacman config: ${target} (${STATE[mirror_source]}/${STATE[mirror_region]})"
}

# Write the installed system's pacman.conf and mirrorlist.  AstraOS packages
# are already installed, so the target does not need the live [astra-local]
# repository.
write_target_pacman_conf() {
	local mnt=$1
	local mirrorlist="${mnt}/etc/pacman.d/mirrorlist"
	[[ -d ${mnt}/etc ]] || die "target /etc is missing; pacstrap did not finish"
	mkdir -p "${mnt}/etc/pacman.d" || die "cannot create target mirrorlist directory"

	{
		cat <<'EOF'
# Generated by the AstraOS installer.
[options]
Architecture = x86_64
HoldPkg = pacman glibc
ParallelDownloads = 3
SigLevel = Required DatabaseOptional
LocalFileSigLevel = Optional
Color
CheckSpace
ILoveCandy
EOF
		cat <<'EOF'

[core]
Include = /etc/pacman.d/mirrorlist

[extra]
Include = /etc/pacman.d/mirrorlist

[multilib]
Include = /etc/pacman.d/mirrorlist
EOF
	} >"${mnt}/etc/pacman.conf" || die "cannot write target pacman.conf"

	if [[ ${STATE[mirror_source]} == "ala" ]]; then
		printf 'Server = https://archive.archlinux.org/repos/%s/$repo/os/$arch\n' \
			"$(read_snapshot)" >"${mirrorlist}"
	else
		while IFS= read -r base; do
			[[ -n ${base} ]] || continue
			printf 'Server = %s/$repo/os/$arch\n' "${base}"
		done < <(mirror_base_urls "${STATE[mirror_region]}") >"${mirrorlist}"
	fi
	chmod 0644 "${mirrorlist}" "${mnt}/etc/pacman.conf" 2>/dev/null || true
	log "wrote target pacman.conf and mirrorlist (${STATE[mirror_source]}/${STATE[mirror_region]})"
}

check_network() {
	if command -v curl >/dev/null 2>&1; then
		curl -fsS --max-time 10 -o /dev/null https://archlinux.org/ 2>/dev/null && return 0
	fi
	if command -v ping >/dev/null 2>&1; then
		ping -c 1 -W 3 archlinux.org >/dev/null 2>&1 && return 0
	fi
	getent hosts archlinux.org >/dev/null 2>&1
}

ensure_network() {
	local attempt=1
	while ((attempt <= 3)); do
		if check_network; then
			log "network check passed"
			return 0
		fi
		printf '\n' >&2
		ui_markdown '## Network required

AstraOS installs packages from the Arch Linux Archive (or a mirror), so the
live session needs an internet connection before the install starts.

Use `nmtui` to connect to Wi-Fi, or plug in an Ethernet cable.' || true
		if ! ui_confirm "Open nmtui to configure the network now?"; then
			break
		fi
		if command -v nmtui >/dev/null 2>&1; then
			nmtui || true
		else
			warn "nmtui is not available; configure the network from another terminal"
			pause
		fi
		attempt=$((attempt + 1))
	done
	die "no network connection. Connect to the internet and run the installer again."
}

ask_package_source() {
	step_header "Package source"
	ui_markdown '## Package source

This only chooses *where packages are downloaded from*. It does not touch
your disks.

- **Arch Linux Archive** uses the exact snapshot pinned by this ISO. It is the
  recommended, reproducible choice.
- **Worldwide mirrors** uses the current Arch mirrors for your region.' || die "could not show package source help"

	local source
	source=$(ui_choose "Package download source" \
		"Arch Linux Archive (pinned snapshot, recommended)" \
		"Worldwide mirrors") || return 1

	case "$source" in
	Arch*)
		STATE[mirror_source]="ala"
		STATE[mirror_region]="Worldwide"
		;;
	Worldwide*)
		STATE[mirror_source]="mirrors"
		local region
		region=$(ui_choose "Select mirror region" \
			"Worldwide" "Europe" "North America" "Asia" "Australia" \
			"South America" "Africa") || return 1
		STATE[mirror_region]="${region:-Worldwide}"
		;;
	*)
		return 1
		;;
	esac

	log "package source: ${STATE[mirror_source]} (${STATE[mirror_region]})"
	ensure_network || return 1
	ui_markdown "Package source: **${STATE[mirror_source]}** (${STATE[mirror_region]})" || true
	return 0
}
